    private final int warmupRuns;
    private final int benchmarkRuns;

    /**
     * Создает экземпляр.

     * @param warmupRuns    количество прогревочных запусков
     * @param benchmarkRuns количество замеров для усреднения
     */
    public PrimeBenchmark(int warmupRuns, int benchmarkRuns) {
        this.warmupRuns = warmupRuns;
        this.benchmarkRuns = benchmarkRuns;
    }

    /**
     * Запускает все бенчмарки и возвращает результаты.

     * @param threadCounts массив количеств потоков для тестирования
     * @return список результатов бенчмарков
     */
    public List<BenchmarkResult> runAllBenchmarks(int[] threadCounts) {
        warmup();

        List<BenchmarkResult> results = new ArrayList<>();
   
        results.add(benchmarkSequential());

        for (int threadCount : threadCounts) {
            results.add(benchmarkThreaded(threadCount));
        }

        results.add(benchmarkStream());

        return results;
    }

    /**
     * Прогрев.
     */
    private void warmup() {
        PrimeDetector detector = new SequentialPrimeDetector();
        for (int i = 0; i < warmupRuns; i++) {
            detector.hasNonPrime(LARGE_PRIMES);
        }
    }

    /**
     * Бенчмарк последовательного детектора.
     */
    private BenchmarkResult benchmarkSequential() {
        PrimeDetector detector = new SequentialPrimeDetector();
        long totalTime = 0;

        for (int i = 0; i < benchmarkRuns; i++) {
            long start = System.nanoTime();
            detector.hasNonPrime(LARGE_PRIMES);
            long end = System.nanoTime();
            totalTime += (end - start);
        }

        long avgTime = totalTime / benchmarkRuns;
        return new BenchmarkResult("Последовательное", avgTime, 1);
    }

    /**
     * Бенчмарк многопоточного детектора.
     */
    private BenchmarkResult benchmarkThreaded(int threadCount) {
        PrimeDetector detector = new ThreadedPrimeDetector(threadCount);
        long totalTime = 0;

        for (int i = 0; i < benchmarkRuns; i++) {
            long start = System.nanoTime();
            detector.hasNonPrime(LARGE_PRIMES);
            long end = System.nanoTime();
            totalTime += (end - start);
        }

        long avgTime = totalTime / benchmarkRuns;
        return new BenchmarkResult("Многопоточное", avgTime, threadCount);
    }

    /**
     * Бенчмарк детектора с parallelStream.
     */
    private BenchmarkResult benchmarkStream() {
        PrimeDetector detector = new StreamPrimeDetector();
        long totalTime = 0;

        for (int i = 0; i < benchmarkRuns; i++) {
            long start = System.nanoTime();
            detector.hasNonPrime(LARGE_PRIMES);
            long end = System.nanoTime();
            totalTime += (end - start);
        }

        long avgTime = totalTime / benchmarkRuns;
        int availableProcessors = Runtime.getRuntime().availableProcessors();
        return new BenchmarkResult("Параллельное", avgTime, availableProcessors);
    }

    /**
     * Выводит.
     */
    public static void printResults(List<BenchmarkResult> results) {
        for (BenchmarkResult result : results) {
            System.out.println(result);
        }
    }
